const mul = (A, B) => [
  [A[0][0] * B[0][0] + A[0][1] * B[1][0], A[0][0] * B[0][1] + A[0][1] * B[1][1]],
  [A[1][0] * B[0][0] + A[1][1] * B[1][0], A[1][0] * B[0][1] + A[1][1] * B[1][1]],
];

// 與快速冪相同，只是把「數字相乘」換成「矩陣相乘」
function matPow(M, n) {
  let R = [[1, 0], [0, 1]];
  for (; n; n >>= 1) {
    if (n & 1) R = mul(R, M);
    M = mul(M, M);
  }
  return R;
}

// [[1,1],[1,0]]^n = [[F(n+1), F(n)], [F(n), F(n-1)]]，O(log n) 求出第 n 項費氏數
const n = 25, R = matPow([[1, 1], [1, 0]], n);
console.log(`M^${n} = [[${R[0][0]}, ${R[0][1]}], [${R[1][0]}, ${R[1][1]}]]`);
console.log(`F(${n}) = ${R[0][1]}`);
